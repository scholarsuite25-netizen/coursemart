/**
 * E2E Test Suite: Zero-Cost Multi-Model AI Router & Failover
 * Requirements: R2 (Zero-Cost Multi-Model AI Routing & API Integration)
 * Test Coverage: Tier 1 (Feature Coverage) & Tier 2 (Boundary & Corner Cases)
 *
 * Styling rule: No spaces before or after '/' between words (e.g. free/paid, FAQ/community, dwc/ngo).
 * Offline isolation: Strictly offline mocks and stubs; zero live paid tokens consumed.
 */

import test, { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import {
  generateAiCompletion,
  GROQ_FREE_MODELS,
  GEMINI_STUDIO_FREE_MODELS,
  OPENROUTER_FREE_MODELS,
  type ModelTier,
} from '../server/aiRouter.ts';

describe('Zero-Cost Multi-Model AI Router & Failover', () => {
  /* ==========================================================================
     Feature 1: Zero-Cost Multi-Model Proxy Routing & Failover
     ========================================================================== */

  describe('Tier 1: Feature Coverage', () => {
    it('T1.1: routes requests to local proxy (http://localhost:8080) with zero paid token consumption', async () => {
      let requestedUrl = '';
      let requestedBody = '';

      const mockFetch: typeof fetch = async (input, init) => {
        requestedUrl = String(input);
        requestedBody = String(init?.body || '');
        return new Response(
          JSON.stringify({
            candidates: [
              {
                content: {
                  parts: [{ text: 'Master modern full-stack development with vibe coding.' }],
                },
              },
            ],
          }),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      };

      const result = await generateAiCompletion({
        prompt: 'Explain vibe coding workflows for web applications',
        modelTier: 'fast',
        mockFetch,
      });

      assert.equal(result.isZeroCost, true);
      assert.equal(result.fallbackOccurred, false);
      assert.match(result.text, /vibe coding/i);
      assert.match(requestedUrl, /http:\/\/localhost:8080\/v1beta\/models\//);
      assert.match(requestedBody, /vibe coding workflows/);
    });

    it('T1.2: fast tier prioritizes Groq free models (qwen3-27b-groq, gpt-oss-120b-groq)', async () => {
      let invokedModel = '';

      const mockFetch: typeof fetch = async (input) => {
        const urlStr = String(input);
        const match = urlStr.match(/\/models\/([^:]+)/);
        if (match) {
          invokedModel = match[1];
        }
        return new Response(
          JSON.stringify({
            candidates: [
              {
                content: {
                  parts: [{ text: 'Fast tier response generated by Groq pool.' }],
                },
              },
            ],
          }),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      };

      const result = await generateAiCompletion({
        prompt: 'Generate an executive summary for AI integration',
        modelTier: 'fast',
        mockFetch,
      });

      assert.equal(result.isZeroCost, true);
      // The first candidate in the fast tier is a Groq model
      assert.ok(
        invokedModel.includes('qwen3-27b-groq') ||
          invokedModel.includes('gpt-oss') ||
          GROQ_FREE_MODELS.some((m) => m.includes(invokedModel)),
        `Invoked model ${invokedModel} should be in Groq free models`
      );
    });

    it('T1.3: creative tier prioritizes Gemini AI Studio free models (gemini-3-8-flash-free, gemini-3-5-flash-free)', async () => {
      let invokedModel = '';

      const mockFetch: typeof fetch = async (input) => {
        const urlStr = String(input);
        const match = urlStr.match(/\/models\/([^:]+)/);
        if (match) {
          invokedModel = match[1];
        }
        return new Response(
          JSON.stringify({
            candidates: [
              {
                content: {
                  parts: [{ text: 'Creative tier response generated by Gemini Studio pool.' }],
                },
              },
            ],
          }),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      };

      const result = await generateAiCompletion({
        prompt: 'Draft an evocative blog hook for tech leaders',
        modelTier: 'creative',
        mockFetch,
      });

      assert.equal(result.isZeroCost, true);
      assert.ok(
        invokedModel.includes('gemini-3-8-flash-free') ||
          invokedModel.includes('gemini-3-5') ||
          GEMINI_STUDIO_FREE_MODELS.some((m) => m.includes(invokedModel)),
        `Invoked model ${invokedModel} should be in Gemini Studio free models`
      );
    });

    it('T1.4: general tier pool includes OpenRouter free models (cohere-code-free, gemma-4-31b-free, ling-flash-free)', () => {
      assert.ok(OPENROUTER_FREE_MODELS.length >= 3);
      assert.ok(OPENROUTER_FREE_MODELS.some((m) => m.includes('cohere')));
      assert.ok(OPENROUTER_FREE_MODELS.some((m) => m.includes('gemma')));
      assert.ok(OPENROUTER_FREE_MODELS.some((m) => m.includes('ling')));
    });

    it('T1.5: systemPrompt properly prepends instructions and guidelines to the prompt payload', async () => {
      let sentPayload = '';

      const mockFetch: typeof fetch = async (input, init) => {
        sentPayload = String(init?.body || '');
        return new Response(
          JSON.stringify({
            candidates: [
              {
                content: {
                  parts: [{ text: 'Strictly structured answer adhering to instructions.' }],
                },
              },
            ],
          }),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      };

      const systemPrompt = 'Answer in under 50 words with no conversational filler.';
      const userPrompt = 'How does Paystack split payments with affiliate promoters?';

      await generateAiCompletion({
        prompt: userPrompt,
        systemPrompt,
        mockFetch,
      });

      assert.ok(sentPayload.includes(systemPrompt));
      assert.ok(sentPayload.includes(userPrompt));
    });

    it('T1.6: offline test mode without mockFetch returns deterministic offline stub with isZeroCost=true', async () => {
      // In offline test runs, preserve zero-token guardrails
      const prevEnv = process.env.NODE_ENV;
      process.env.NODE_ENV = 'test';
      try {
        const result = await generateAiCompletion({
          prompt: 'Describe how DWC handles digital asset downloads and security',
        });

        assert.equal(result.isZeroCost, true);
        assert.equal(result.fallbackOccurred, false);
        assert.match(result.modelUsed, /deterministic-offline-stub/);
        assert.ok(result.text.length > 0);
      } finally {
        process.env.NODE_ENV = prevEnv;
      }
    });
  });

  describe('Tier 2: Boundary & Corner Cases', () => {
    it('T2.1: 429 rate limit failover seamlessly switches to next free model in chain', async () => {
      const calls: string[] = [];

      const mockFetch: typeof fetch = async (input) => {
        const urlStr = String(input);
        const match = urlStr.match(/\/models\/([^:]+)/);
        const modelName = match ? match[1] : 'unknown';
        calls.push(modelName);

        // First call hits 429 rate limit
        if (calls.length === 1) {
          return new Response(
            JSON.stringify({ error: { code: 429, message: 'Rate limit exceeded on Groq model' } }),
            { status: 429, headers: { 'Content-Type': 'application/json' } }
          );
        }

        // Second model succeeds
        return new Response(
          JSON.stringify({
            candidates: [
              {
                content: {
                  parts: [{ text: 'Successfully recovered via secondary model in failover chain.' }],
                },
              },
            ],
          }),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      };

      const result = await generateAiCompletion({
        prompt: 'Explain automated social media syndication',
        modelTier: 'fast',
        mockFetch,
      });

      assert.equal(result.isZeroCost, true);
      assert.equal(result.fallbackOccurred, true);
      assert.equal(calls.length, 2, 'Should have attempted secondary model after 429');
      assert.match(result.text, /recovered via secondary model/);
    });

    it('T2.2: 503 service unavailable failover tries subsequent model provider without throwing', async () => {
      const calls: string[] = [];

      const mockFetch: typeof fetch = async (input) => {
        const urlStr = String(input);
        const match = urlStr.match(/\/models\/([^:]+)/);
        const modelName = match ? match[1] : 'unknown';
        calls.push(modelName);

        // First model returns 503
        if (calls.length === 1) {
          return new Response(
            JSON.stringify({ error: { code: 503, message: 'Model overloaded' } }),
            { status: 503, headers: { 'Content-Type': 'application/json' } }
          );
        }

        return new Response(
          JSON.stringify({
            candidates: [
              {
                content: {
                  parts: [{ text: 'Recovered after 503 service outage.' }],
                },
              },
            ],
          }),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      };

      const result = await generateAiCompletion({
        prompt: 'How do LMS cohort discussions operate?',
        mockFetch,
      });

      assert.equal(result.isZeroCost, true);
      assert.equal(result.fallbackOccurred, true);
      assert.match(result.text, /Recovered after 503/);
    });

    it('T2.3: connection timeout or network abort triggers transparent fallback to subsequent model', async () => {
      let callCount = 0;

      const mockFetch: typeof fetch = async () => {
        callCount++;
        if (callCount === 1) {
          throw new Error('Connection aborted by timeout');
        }
        return new Response(
          JSON.stringify({
            candidates: [
              {
                content: {
                  parts: [{ text: 'Recovered after connection timeout.' }],
                },
              },
            ],
          }),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      };

      const result = await generateAiCompletion({
        prompt: 'How to build high-converting sales funnels?',
        mockFetch,
      });

      assert.equal(result.isZeroCost, true);
      assert.equal(result.fallbackOccurred, true);
      assert.match(result.text, /Recovered after connection timeout/);
    });

    it('T2.4: all-provider failure fallback returns deterministic fallback text with isZeroCost=true and fallbackOccurred=true', async () => {
      // Every model returns an error
      const mockFetch: typeof fetch = async () => {
        return new Response(
          JSON.stringify({ error: { code: 500, message: 'Internal Server Error' } }),
          { status: 500, headers: { 'Content-Type': 'application/json' } }
        );
      };

      const customFallback = 'Deterministic offline answer: Consult our documentation for full details.';
      const result = await generateAiCompletion({
        prompt: 'What is the refund turnaround time?',
        fallbackText: customFallback,
        mockFetch,
      });

      assert.equal(result.isZeroCost, true);
      assert.equal(result.fallbackOccurred, true);
      assert.equal(result.text, customFallback);
      assert.equal(result.modelUsed, 'deterministic-fallback');
    });

    it('T2.5: token clamping and maxTokens generationConfig enforcement', async () => {
      let capturedBody: any = null;

      const mockFetch: typeof fetch = async (input, init) => {
        capturedBody = JSON.parse(String(init?.body || '{}'));
        return new Response(
          JSON.stringify({
            candidates: [
              {
                content: {
                  parts: [{ text: 'Short clamped answer.' }],
                },
              },
            ],
          }),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      };

      await generateAiCompletion({
        prompt: 'Provide a concise overview of prompt engineering',
        maxTokens: 256,
        mockFetch,
      });

      assert.ok(capturedBody);
      assert.equal(capturedBody.generationConfig?.maxOutputTokens, 256);
    });

    it('T2.6: empty prompt handling returns deterministic fallback without attempting network requests', async () => {
      let networkAttempted = false;

      const mockFetch: typeof fetch = async () => {
        networkAttempted = true;
        return new Response('{}', { status: 200 });
      };

      const result = await generateAiCompletion({
        prompt: '   ',
        mockFetch,
      });

      assert.equal(networkAttempted, false, 'Should not issue network requests for empty prompt');
      assert.equal(result.isZeroCost, true);
      assert.equal(result.modelUsed, 'deterministic-fallback');
      assert.match(result.text, /No prompt provided/);
    });
  });
});
